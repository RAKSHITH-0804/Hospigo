export type OpdErrorCode = (typeof OpdErrorCode)[keyof typeof OpdErrorCode];

export function opdError(
  status: number,
  code: OpdErrorCode,
  extra?: Record<string, unknown>,
): HttpException {
  return new HttpException({ statusCode: status, code, ...extra }, status);
}
